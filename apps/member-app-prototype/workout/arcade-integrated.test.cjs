/* GO Workout Arcade V1.2 integrated presentation regression suite. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
global.window={};
const arcade=require('./arcade.js');
const integrated=require('./arcade-integrated.js');
const history=[{id:'w-1',completionStatus:'complete',completedSets:6},{id:'w-2',completionStatus:'complete',completedSets:8}];
const training={arcade:{mode:'arcade',outfit:'explorer'}};
const stats=arcade.stats(history);
assert.equal(stats.xp,225,'Canonical 200 base XP plus first mission reward only');
const avatar='<span class="test-avatar">🏋️</span>';
const home=integrated.homePanel(training,history,avatar,{nextWorkout:'Full Body A'});
assert.match(home,/Full Body A/);
assert.match(home,/LEVEL 1/);
assert.match(home,/225 XP/);
assert.match(home,/CHARACTER LOCKER/);
assert.match(home,/data-arcade-action="mode" data-arcade-value="arcade" aria-pressed="true"/);
assert.match(home,/data-arcade-value="focus"/);
assert.match(home,/test-avatar/,'Uses the existing workout avatar');
const active={routineName:'Recovery-adjusted strength',exercises:[{sets:[{completed:true},{completed:false},{completed:false}]}]};
const activeHome=integrated.homePanel(training,history,avatar,{activeWorkout:active});
assert.match(activeHome,/2 prescribed sets remaining/);
const train=integrated.trainPanel(training,history,avatar,{activeWorkout:active});
assert.match(train,/Recovery-adjusted strength/);
assert.match(train,/1 of 3 sets recorded/);
assert.match(train,/225 XP/);
const progress=integrated.progressPanel(training,history,{block:2,week:3,completed:1,planned:4});
assert.match(progress,/BLOCK 2 · CHAPTER 3 OF 4/);
assert.match(progress,/1 of 4 workouts completed this week/);
assert.match(progress,/First mission/);
assert.match(progress,/Find your rhythm/);
assert.match(progress,/Building strength/);
assert.match(progress,/Earned · \+25 XP/);
assert.match(progress,/2 \/ 3 workouts/,'Next milestone is still locked');
assert.match(progress,/14 \/ 20 sets/,'Set milestone uses actual completed sets');
assert.equal((progress.match(/class="ai-chapter /g)||[]).length,4);
assert.equal((progress.match(/is-current/g)||[]).length,1);
assert.equal(arcade.stats(history).xp,stats.xp,'Presentation does not create new XP');
const hostile=integrated.homePanel(training,history,avatar,{nextWorkout:'<img src=x onerror=alert(1)>'});
assert.doesNotMatch(hostile,/<img src=x/,'Workout labels are escaped');
const focus={arcade:{mode:'focus',outfit:'explorer'}};
assert.match(integrated.homePanel(focus,history,avatar),/Training first/);
assert.doesNotMatch(integrated.homePanel(focus,history,avatar),/test-avatar/,'Focus mode does not show character imagery');
assert.doesNotMatch(integrated.trainPanel(focus,history,avatar),/ai-train-score/,'Focus mode keeps Train quiet');
assert.match(integrated.progressPanel(focus,history,{block:1,week:1}),/ai-mode-focus/);
const companion={arcade:{mode:'companion',outfit:'spark'}};
assert.match(integrated.homePanel(companion,history,avatar),/ai-mode-companion/);
assert.match(integrated.homePanel(companion,history,avatar),/test-avatar/);
const app=fs.readFileSync(path.join(__dirname,'app.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
const arcadeJs=fs.readFileSync(path.join(__dirname,'arcade.js'),'utf8');
const css=fs.readFileSync(path.join(__dirname,'arcade-integrated.css'),'utf8');
for(const method of ['homePanel','trainPanel','progressPanel'])assert.match(app,new RegExp('GoWorkoutArcadeIntegrated\\.'+method));
assert.match(app,/CHARACTER LOCKER/);
assert.match(html,/arcade-integrated\.js\?v=/);
assert.match(html,/arcade-integrated\.css\?v=/);
assert.ok(html.indexOf('arcade.js')<html.indexOf('arcade-integrated.js')&&html.indexOf('arcade-integrated.js')<html.indexOf('app.js'),'Integrated module is loaded after Arcade and before app');
assert.match(arcadeJs,/setting\.battleCollapsed===false\?battle:''/,'Full battle is hidden until explicitly expanded');
assert.match(arcadeJs,/Character Locker/);
assert.match(css,/\.ai-mode-picker button\.is-active/);
console.log('GO Workout Arcade V1.2 integrated experience tests passed.');